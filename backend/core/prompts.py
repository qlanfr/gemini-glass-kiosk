DEFAULT_PROMPT_ID = "kio_friendly"


def get_prompt(prompt_id: str) -> PromptConfig:
    """프롬프트 ID로 설정 가져오기"""
    return PROMPTS.get(prompt_id, PROMPTS[DEFAULT_PROMPT_ID])


def get_instruction(prompt_id: str) -> str:
    """프롬프트 ID로 시스템 지시문만 가져오기"""
    return get_prompt(prompt_id).instruction


def list_prompts() -> List[Dict]:
    """모든 프롬프트 목록 반환 (API용)"""
    return [
        {
            "id": p.id,
            "name": p.name,
            "description": p.description,
            "language": p.language,
            "icon": p.icon,
        }
        for p in PROMPTS.values()
    ]
